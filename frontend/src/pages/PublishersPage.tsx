import { useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { DollarSign, Globe, TrendingUp, Award, BarChart3 } from 'lucide-react'
import { useTopPublishers } from '../api/client'
import { Card, CardHeader, CardTitle, CardContent } from '../components/ui/Card'
import { MetricCard } from '../components/ui/MetricCard'
import { DataTable, type Column } from '../components/ui/DataTable'
import { Skeleton, CardSkeleton, TableSkeleton } from '../components/ui/Skeleton'
import { formatCurrency } from '../lib/utils'
import type { PublisherSummary } from '../types/publisher'
import { useTranslation } from '../i18n/context'

function formatBacino(value: number): string {
  if (value >= 1_000_000) return `${(value / 1_000_000).toFixed(1)}M`
  if (value >= 1_000) return `${(value / 1_000).toFixed(0)}K`
  return String(value)
}

const MONTH_LABELS = [
  'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
  'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec',
]

export function PublishersPage() {
  const [year, setYear] = useState(2026)
  const [month, setMonth] = useState<number | undefined>(undefined)
  const navigate = useNavigate()
  const { data: publishers, isLoading, error } = useTopPublishers(year, month)
  const { t } = useTranslation()

  if (isLoading) {
    return (
      <div className="space-y-6">
        <Skeleton className="h-8 w-64" />
        <div className="grid grid-cols-1 gap-4 md:grid-cols-2 lg:grid-cols-5">
          {Array.from({ length: 5 }).map((_, i) => (
            <CardSkeleton key={i} />
          ))}
        </div>
        <Card>
          <CardHeader>
            <Skeleton className="h-6 w-64" />
          </CardHeader>
          <CardContent className="p-0">
            <TableSkeleton rows={10} columns={7} />
          </CardContent>
        </Card>
      </div>
    )
  }

  if (error) {
    return (
      <div className="py-12 text-center">
        <p className="text-red-500">Failed to load publisher data.</p>
      </div>
    )
  }

  const data = publishers ?? []

  const totalRevenue = data.reduce((sum, p) => sum + p.total_revenue, 0)
  const totalBacino = data.reduce((sum, p) => sum + p.total_bacino, 0)
  const totalImpressions = data.reduce((sum, p) => sum + p.total_impressions, 0)
  const weightedEcpm = totalImpressions > 0 ? (totalRevenue / totalImpressions) * 1000 : 0
  const avgFillRate = data.length > 0 ? data.reduce((sum, p) => sum + p.fill_rate, 0) / data.length : 0

  const columns: Column<PublisherSummary & { rank: number }>[] = [
    {
      key: 'rank',
      header: '#',
      className: 'w-12 text-center',
      headerTitle: 'Revenue ranking position',
      render: (row) => (
        <span className="tabular-nums text-xs text-slate-400">{row.rank}</span>
      ),
    },
    {
      key: 'publisher_id',
      header: 'Publisher',
      sortable: true,
      headerTitle: 'Publisher name in the Adkaora network',
      render: (row) => (
        <span className="font-semibold text-slate-900">{row.publisher_id}</span>
      ),
    },
    {
      key: 'country',
      header: 'Country',
      sortable: true,
      headerTitle: 'Publisher primary country by revenue volume (dominant geo cluster)',
      render: (row) => {
        const flag = row.dominant_geo === 'ITA' ? '🇮🇹' : row.dominant_geo === 'ES' ? '🇪🇸' : '🌎'
        return (
          <span className="text-sm">
            <span className="mr-1.5">{flag}</span>
            {row.country}
          </span>
        )
      },
    },
    {
      key: 'total_revenue',
      header: 'Revenue',
      sortable: true,
      className: 'text-right',
      headerTitle: 'Net revenue (publisher share after 60/40 revenue split) for the selected period',
      render: (row) => (
        <span className="tabular-nums">{formatCurrency(row.total_revenue)}</span>
      ),
    },
    {
      key: 'total_bacino',
      header: 'Bacino',
      sortable: true,
      className: 'text-right',
      headerTitle: 'Total ad requests (ad pool): number of ad requests generated by the site/app',
      render: (row) => (
        <span className="tabular-nums text-xs">{formatBacino(row.total_bacino)}</span>
      ),
    },
    {
      key: 'revenue_share_pct',
      header: 'Share %',
      sortable: true,
      className: 'text-right',
      headerTitle: 'Revenue share relative to the total of all publishers in the network',
      render: (row) => (
        <span className="tabular-nums text-xs">{row.revenue_share_pct.toFixed(1)}%</span>
      ),
    },
    {
      key: 'ecpm',
      header: 'eCPM',
      sortable: true,
      className: 'text-right',
      headerTitle: 'Effective Cost Per Mille: net revenue per 1000 served impressions. Indicates the average value of each impression',
      render: (row) => (
        <span className="tabular-nums">{row.ecpm.toFixed(2)}&euro;</span>
      ),
    },
    {
      key: 'avg_marginality',
      header: 'RPM',
      sortable: true,
      className: 'text-right',
      headerTitle: 'Revenue Per Mille: net revenue per 1000 ad requests (supply). Measures overall traffic monetization',
      render: (row) => (
        <span className="tabular-nums">{row.avg_marginality.toFixed(2)}&euro;</span>
      ),
    },
    {
      key: 'fill_rate',
      header: 'Fill Rate',
      sortable: true,
      className: 'text-right',
      headerTitle: 'Impressions / Ad Requests: percentage of ad requests actually filled with an ad. Typical values: 40-70%',
      render: (row) => (
        <span className="tabular-nums text-xs">{(row.fill_rate * 100).toFixed(1)}%</span>
      ),
    },
    {
      key: 'google_pct',
      header: 'Google %',
      sortable: true,
      className: 'text-right',
      headerTitle: 'Percentage of revenue from the Google AdExchange channel. High values (>60%) indicate dependency on a single channel',
      render: (row) => (
        <span className="tabular-nums text-xs">{row.google_pct.toFixed(1)}%</span>
      ),
    },
    {
      key: 'trend_4w',
      header: 'Trend 4w',
      sortable: true,
      className: 'text-right',
      headerTitle: 'Revenue change over the last 4 weeks vs the previous 4 weeks. Indicates publisher momentum',
      render: (row) => {
        if (row.trend_4w === null) return <span className="text-slate-400">-</span>
        const color = row.trend_4w > 0 ? 'text-green-600' : row.trend_4w < -5 ? 'text-red-600' : 'text-slate-600'
        return (
          <span className={`tabular-nums text-xs ${color}`}>
            {row.trend_4w > 0 ? '+' : ''}{row.trend_4w.toFixed(1)}%
          </span>
        )
      },
    },
  ]

  const rankedData = data.map((p, i) => ({ ...p, rank: i + 1 }))

  const selectClass = 'cursor-pointer rounded-md border border-slate-200 bg-slate-50 px-3 py-1.5 text-sm font-medium text-slate-700 shadow-sm transition-colors duration-150 hover:bg-slate-100 focus:border-blue-400 focus:outline-none focus:ring-2 focus:ring-blue-100'

  return (
    <div className="space-y-6">
      {/* Stats Row */}
      <div className="grid grid-cols-1 gap-4 md:grid-cols-2 lg:grid-cols-5">
        <MetricCard
          label={t('publishers.total_revenue')}
          value={totalRevenue}
          format="currency"
          subtitle={t('publishers.top_n_publishers', String(data.length))}
          icon={<DollarSign size={18} />}
          iconBg="bg-emerald-50"
          iconColor="text-emerald-500"
          accentColor="bg-emerald-500"
        />
        <MetricCard
          label={t('publishers.total_bacino')}
          value={totalBacino}
          format="number"
          subtitle={t('publishers.ad_requests')}
          icon={<Globe size={18} />}
          iconBg="bg-blue-50"
          iconColor="text-blue-500"
          accentColor="bg-blue-500"
        />
        <MetricCard
          label={t('publishers.avg_ecpm')}
          value={weightedEcpm}
          format="currency_decimal"
          subtitle={t('publishers.weighted_average')}
          icon={<TrendingUp size={18} />}
          iconBg="bg-violet-50"
          iconColor="text-violet-500"
          accentColor="bg-violet-500"
        />
        <Card className="relative overflow-hidden">
          <div className="absolute left-0 top-0 h-full w-1 rounded-l-lg bg-amber-500" />
          <div className="flex items-start justify-between px-5 py-4">
            <div className="min-w-0 space-y-0.5">
              <p className="text-xs font-medium uppercase tracking-wide text-slate-500">{t('publishers.top_publisher')}</p>
              <p className="truncate text-xl font-bold text-slate-900">{data[0]?.publisher_id ?? '-'}</p>
              <p className="text-xs text-slate-400">{data[0] ? formatCurrency(data[0].total_revenue) : ''}</p>
            </div>
            <div className="flex-shrink-0 rounded-lg bg-amber-50 p-2 text-amber-500">
              <Award size={18} />
            </div>
          </div>
        </Card>
        <MetricCard
          label={t('publishers.avg_fill_rate')}
          value={avgFillRate * 100}
          format="percent"
          subtitle={t('publishers.imp_ad_requests')}
          icon={<BarChart3 size={18} />}
          iconBg="bg-cyan-50"
          iconColor="text-cyan-500"
          accentColor="bg-cyan-500"
        />
      </div>

      {/* Publishers Table */}
      <Card>
        <CardHeader>
          <div className="flex items-center justify-between">
            <CardTitle>{t('publishers.top_n_publishers', String(data.length))} {t('publishers.by_revenue')}</CardTitle>
            <div className="flex items-center gap-2">
              <select
                value={month ?? ''}
                onChange={(e) => {
                  const v = e.target.value
                  setMonth(v ? Number(v) : undefined)
                }}
                className={selectClass}
                aria-label="Select month"
              >
                <option value="">{t('publishers.all_months')}</option>
                {MONTH_LABELS.map((label, i) => (
                  <option key={i + 1} value={i + 1}>{label}</option>
                ))}
              </select>
              <select
                value={year}
                onChange={(e) => setYear(Number(e.target.value))}
                className={selectClass}
                aria-label="Select year"
              >
                <option value={2026}>2026</option>
                <option value={2025}>2025</option>
                <option value={2024}>2024</option>
              </select>
            </div>
          </div>
        </CardHeader>
        <CardContent className="p-0">
          {data.length === 0 ? (
            <div className="py-12 text-center text-slate-500">
              {t('publishers.no_data', String(year))}
            </div>
          ) : (
            <DataTable
              data={rankedData}
              columns={columns}
              keyExtractor={(row) => row.publisher_id}
              onRowClick={(row) => navigate(`/publishers/${row.publisher_id}`)}
            />
          )}
        </CardContent>
      </Card>
    </div>
  )
}
